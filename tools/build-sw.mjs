// One-off: regenerate sw.js so its precache list and cache name always match the files
// on disk.
//
// Run:  node tools/build-sw.mjs

import { readdir, stat, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'sw.js');

const INCLUDE_DIRS = ['styles', 'fonts', 'js', 'images', 'icons'];
const INCLUDE_FILES = ['index.html', 'manifest.webmanifest', 'sw.js'];

async function walk(dir, out = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) await walk(full, out);
    else out.push(full);
  }
  return out;
}

async function main() {
  const files = [];
  for (const name of INCLUDE_FILES) files.push(path.join(ROOT, name));
  for (const dir of INCLUDE_DIRS) {
    const full = path.join(ROOT, dir);
    try {
      await stat(full);
    } catch {
      continue;
    }
    files.push(...(await walk(full)));
  }

  const assets = files
    .map((file) => `./${path.relative(ROOT, file).split(path.sep).join('/')}`)
    .sort();

  // The cache name is derived from the bytes on disk, so any build that changes an asset
  // automatically invalidates the previous cache. A hand-bumped version string is how a
  // stale copy ends up stuck in front of someone.
  const stamps = [];
  for (const file of [...files].sort()) {
    const rel = path.relative(ROOT, file).split(path.sep).join('/');
    if (rel === 'sw.js') continue;
    const info = await stat(file);
    stamps.push(`${rel}:${info.size}:${Math.round(info.mtimeMs)}`);
  }
  const version = createHash('sha256').update(stamps.join('|')).digest('hex').slice(0, 8);
  const cacheName = `prana-${version}`;

  const source = `// Generated by tools/build-sw.mjs — do not edit by hand.
// Cache: ${cacheName} (a hash of every shipped file)

const CACHE = '${cacheName}';

const ASSETS = [
  './',
${assets.map((asset) => `  '${asset}',`).join('\n')}
];

// Fetched with cache: 'reload' so a new build never mixes fresh files with ones the
// browser's HTTP cache is still holding on to.
async function precache() {
  const cache = await caches.open(CACHE);
  const failures = [];

  await Promise.all(
    ASSETS.map(async (url) => {
      for (let attempt = 0; attempt < 2; attempt += 1) {
        try {
          const response = await fetch(url, { cache: 'reload' });
          if (!response.ok) throw new Error(response.status + ' ' + url);
          await cache.put(url, response);
          return;
        } catch (error) {
          if (attempt === 1) failures.push(String(error));
        }
      }
    })
  );

  // A half-filled cache is worse than an old working one, so leave the previous worker
  // in place rather than activating something incomplete.
  if (failures.length) throw new Error('precache failed: ' + failures.join(', '));
}

self.addEventListener('install', (event) => {
  event.waitUntil(precache().then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((cached) => {
      if (cached) return cached;
      return fetch(request)
        .then((response) => {
          if (response && response.status === 200 && response.type === 'basic') {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => {
          if (request.mode === 'navigate') {
            return caches.match('./index.html');
          }
          return new Response('', { status: 504, statusText: 'Offline' });
        });
    })
  );
});
`;

  await writeFile(OUT, source);
  console.log(`wrote sw.js — ${assets.length} entries, cache ${cacheName}`);
}

main();
