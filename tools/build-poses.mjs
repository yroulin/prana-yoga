// One-off asset preparation: merge the English source text scraped from yogaphilippines.com
// with the authored metadata and Spanish translations in tools/pose-meta.json.
//
// Run:  node tools/build-poses.mjs
// Out:  js/data/poses.js
//
// The output is committed. The app itself never runs this.

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SOURCE = path.join(ROOT, 'tools', 'out', 'poses.source.json');
const META = path.join(ROOT, 'tools', 'pose-meta.json');
const OUT = path.join(ROOT, 'js', 'data', 'poses.js');

const cleanName = (name) => {
  const afterColon = name.includes(': ') ? name.split(': ').pop() : name;
  return afterColon.trim();
};

async function main() {
  const source = JSON.parse(await readFile(SOURCE, 'utf8'));
  const meta = JSON.parse(await readFile(META, 'utf8'));
  const metaPoses = Object.fromEntries(
    Object.entries(meta).filter(([key]) => !key.startsWith('_'))
  );

  const byId = new Map(source.map((s) => [s.id, s]));
  const poses = [];

  for (const [id, m] of Object.entries(metaPoses)) {
    const s = byId.get(id);
    if (!s) throw new Error(`no source page for ${id}`);
    if (!s.steps?.length) throw new Error(`no source steps for ${id}`);
    for (const i of m.steps) {
      if (!s.steps[i]) throw new Error(`${id}: source step ${i} does not exist`);
    }

    poses.push({
      id,
      name: { en: cleanName(s.name), es: m.nameEs },
      sanskrit: s.sanskrit,
      level: m.level,
      phase: m.phase,
      baseSec: m.baseSec,
      helps: m.helps,
      loads: m.loads,
      sessions: m.sessions,
      cue: { en: m.cueEn, es: m.cueEs },
      steps: {
        en: m.steps.map((i) => s.steps[i]),
        es: m.stepsEs,
      },
      care: { en: m.careEn, es: m.careEs },
      img: `images/poses/${id}.webp`,
      stepsImg: `images/poses/${id}-steps.webp`,
      source: s.source,
    });
  }

  const header = `// Generated by tools/build-poses.mjs — do not edit by hand.
//
// Pose drawings and step strips are by YogaPhilippines.com, reused under CC BY 4.0.
// The licence asks for the credit and a link to the source page to travel with every
// drawing; \`source\` below is that link and the UI renders the credit next to each pose.
//
// English step text is taken from the source pages. Spanish translations, breath cues and
// care notes are authored for this app.

export const CREDIT = 'Drawing: YogaPhilippines.com, CC BY 4.0';
export const CREDIT_URL = 'https://yogaphilippines.com/image-license/';

export const POSES = [`;

  const body = poses
    .map((p) => {
      const o = {
        id: p.id,
        name: p.name,
        sanskrit: p.sanskrit,
        level: p.level,
        phase: p.phase,
        baseSec: p.baseSec,
        helps: p.helps,
        loads: p.loads,
        sessions: p.sessions,
        cue: p.cue,
        steps: p.steps,
        care: p.care,
        img: p.img,
        stepsImg: p.stepsImg,
        source: p.source,
      };
      return `  ${JSON.stringify(o)},`;
    })
    .join('\n');

  await writeFile(OUT, `${header}${body}\n];\n`);
  console.log(`wrote ${path.relative(ROOT, OUT)} — ${poses.length} poses`);
}

main();
